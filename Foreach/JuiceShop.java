class JuiceShop {
    public static void main(String[] args) {
        String juices[] = {
            "Orange", "Apple", "Grape", "Mango", "Pineapple", "Watermelon",
            "Lime", "Strawberry", "Banana", "Pomegranate", "Kiwi", "Papaya",
            "Mixed Fruit", "Sugarcane", "Carrot"
        };

        for (String juice : juices) {
            System.out.println(juice);
        }
    }
}
