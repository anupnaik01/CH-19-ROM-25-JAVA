class SpiceShop {
    public static void main(String[] args) {
        String spices[] = {
            "Turmeric", "Chili Powder", "Coriander", "Cumin", "Black Pepper", "Cardamom",
            "Cloves", "Fenugreek", "Mustard", "Cinnamon", "Fennel", "Bay Leaf", "Asafoetida", "Dry Ginger"
        };

        for (String spice : spices) {
            System.out.println(spice);
        }
    }
}
