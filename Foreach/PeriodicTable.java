class PeriodicTable {
    public static void main(String[] args) {
        String[] elements = {
            "Hydrogen", "Helium", "Lithium", "Beryllium", "Boron", "Carbon",
            "Nitrogen", "Oxygen", "Fluorine", "Neon", "Sodium", "Magnesium"
        };

        for (String element : elements) {
            System.out.println(element);
        }
    }
}
